import { describe, expect, it } from 'vitest';
import { redactSensitiveText } from '../src/utils/redact';

describe('redactSensitiveText', () => {
  describe('ต้องปิด', () => {
    const cases: [string, string][] = [
      ['เบอร์ติดกัน', '0812345678'],
      ['เบอร์มีขีด', '081-234-5678'],
      ['เบอร์เว้นวรรค', '081 234 5678'],
      ['เลขบัญชีมีขีด', '123-4-56789-0'],
      ['บัตรเครดิตเว้นวรรค', '1234 5678 9012 3456'],
      ['บัตรเครดิตมีขีด', '1234-5678-9012-3456'],
      ['เลขบัตรประชาชนติดกัน', '1234567890123'],
      ['เลขบัตรประชาชนมีขีด', '1-2345-67890-12-3'],
    ];

    it.each(cases)('%s: %s', (_label, value) => {
      expect(redactSensitiveText(`ข้อมูลคือ ${value} ครับ`)).toBe('ข้อมูลคือ [REDACTED] ครับ');
    });
  });

  describe('ต้องไม่ปิด (เป็นข้อมูลที่ AI ต้องอ่าน)', () => {
    const cases: [string, string][] = [
      ['จำนวนเงินสั้น', 'กาแฟ 80'],
      ['จำนวนเงินมี comma', 'ซื้อของ 1,250'],
      ['จำนวนเงินมีทศนิยม', 'ค่าไฟ 1250.50'],
      ['จำนวนเงินหลักหมื่น', '+เงินเดือน 35000'],
      ['วันที่ ISO', 'วันที่ 2026-09-14'],
      ['ข้อความไม่มีตัวเลข', 'กาแฟเย็นแก้วนึง'],
    ];

    it.each(cases)('%s: %s', (_label, value) => {
      expect(redactSensitiveText(value)).toBe(value);
    });
  });

  it('ปิดได้หลายจุดในข้อความเดียว', () => {
    expect(redactSensitiveText('โอนจาก 1234567890 ไป 0987654321')).toBe(
      'โอนจาก [REDACTED] ไป [REDACTED]'
    );
  });

  it('ไม่แตะจำนวนเงินที่อยู่ในประโยคเดียวกับเบอร์โทร', () => {
    expect(redactSensitiveText('โอน 250 ไปเบอร์ 0812345678')).toBe('โอน 250 ไปเบอร์ [REDACTED]');
  });
});
