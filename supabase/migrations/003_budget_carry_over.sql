-- ใครรับผิดชอบ: ② Database
-- อ้างอิง: src/services/budget.service.ts carryOverBudgets()
--
-- ทำไมต้องมีไฟล์นี้: งบเก็บเป็นรายเดือน (budgets.month) แล้วไม่มีอะไรยกไปเดือนใหม่
-- ผู้ใช้ทดสอบตั้งงบไว้ พอขึ้นเดือนใหม่ทุกหมวดกลายเป็น "ยังไม่ตั้งงบ" ทั้งหมด
--
-- ตอนนี้โค้ดคัดลอกงบล่าสุดของแต่ละหมวดมาให้เดือนใหม่เองตอนเปิดดูครั้งแรก
-- ปัญหาคือถ้าผู้ใช้ "ยกเลิกงบ" แล้วเราแค่ลบแถวของเดือนนี้ทิ้ง ครั้งถัดไปโค้ดจะไปเจองบ
-- ของเดือนก่อน แล้วคัดลอกกลับมาใหม่ — งบที่ยกเลิกไปแล้วฟื้นขึ้นมาเอง
--
-- ทางแก้: เก็บการยกเลิกเป็นแถวที่ limit_amount = 0 ("ยกเลิกตั้งแต่เดือนนี้")
-- โค้ดทุกจุดถือว่า 0 = ไม่มีงบ และการยกไปเดือนถัดไปจะหยุดที่แถวนี้
--
-- 001_init.sql ระบุว่าห้ามแก้หลัง merge แล้ว จึงแยกมาเป็นไฟล์ใหม่ตามกติกา
-- ⚠️ ก่อนรันไฟล์นี้ ปุ่ม "ยกเลิกงบ" ยังทำงานแบบเดิม (ลบแถวทิ้ง) งบจึงอาจฟื้นในเดือนถัดไป

alter table budgets drop constraint if exists budgets_limit_amount_check;
alter table budgets add constraint budgets_limit_amount_check check (limit_amount >= 0);
