// 🔴 แก้บั๊ก: regex เดิมจับได้แค่ตัวเลข "ติดกันล้วนๆ" ทำให้เลขที่คนพิมพ์จริงหลุดหมด
//   เดิม: redact("บัตร 1234 5678 9012") -> "บัตร 1234 5678 9012"  (ไม่ถูกปิด!)
//   ตอนนี้: -> "บัตร [REDACTED]"
//   และบรรทัด \b\d{13}\b เดิมเป็น dead code เพราะ \d{10,16} จับไปก่อนเสมอ จึงลบทิ้ง
//
// หลักการเลือกเกณฑ์: ตัวเลข 9 หลักขึ้นไปที่คั่นด้วยเว้นวรรคหรือขีดได้ ครอบคลุมทั้ง
//   เบอร์โทร (10), เลขบัญชี (10-12), เลขบัตรเครดิต (13-19), เลขบัตรประชาชน (13)
// จงใจ "ไม่" นับ comma เป็นตัวคั่น เพราะ comma ใช้คั่นหลักพันของจำนวนเงิน ("1,250")
//   ซึ่งเป็นข้อมูลที่ต้องส่งให้ AI อ่าน ไม่ใช่ความลับ
// เกณฑ์นี้ยอม "ปิดเกินดีกว่าปิดขาด" ตาม G5 — จำนวนเงิน 9 หลัก (100 ล้านบาทขึ้นไป)
//   อาจโดนปิดไปด้วย ซึ่งเกินเพดาน MAX_AMOUNT_SATANG (10 ล้านบาท) อยู่แล้ว

/**
 * ตัวเลข 9-19 หลัก โดยระหว่างหลักมีเว้นวรรคหรือขีดคั่นได้ไม่เกิน 1 ตัว
 * ตัวอย่างที่จับได้: 0812345678 / 081-234-5678 / 1234 5678 9012 3456 / 1-2345-67890-12-3
 */
const SENSITIVE_NUMBER = /\d(?:[ -]?\d){8,18}/g;

export function redactSensitiveText(input: string): string {
  return input.replace(SENSITIVE_NUMBER, '[REDACTED]');
}
