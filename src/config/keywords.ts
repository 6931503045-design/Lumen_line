/** คำไทยที่สั้นกว่านี้ จับได้แค่แบบตรงทั้งข้อความ (ดูเหตุผลด้านบน) */
const MIN_THAI_SUBSTRING_LENGTH = 3;

/** คำไทยเรียงยาว → สั้น ให้คำยาวชนะก่อน ("ค่าน้ำ" ก่อน "น้ำ") — คำนวณครั้งเดียวตอนโหลด */
const THAI_KEYS_LONGEST_FIRST = Object.keys(CATEGORY_HINTS)
  .filter((key) => /[฀-๿]/.test(key) && key.length >= MIN_THAI_SUBSTRING_LENGTH)
  .sort((a, b) => b.length - a.length);

/**
 * คำใบ้ชื่อหมวดจากข้อความที่ผู้ใช้พิมพ์ (ไทยหรืออังกฤษ) — null ถ้าไม่มีคำไหนตรงตาราง
 */
export function categoryHint(text: string): string | null {
  const lower = text.trim().toLowerCase();
  if (!lower) return null;

  const whole = CATEGORY_HINTS[lower];
  if (whole) return whole;

  // ไล่จากคำท้ายมาหน้า — ภาษาอังกฤษคำหลักอยู่ท้าย: "water bill" คือบิล ไม่ใช่น้ำดื่ม
  for (const word of lower.split(/[^a-z0-9-]+/).reverse()) {
    const hit = word ? CATEGORY_HINTS[word] : undefined;
    if (hit) return hit;
  }

  const thaiKey = THAI_KEYS_LONGEST_FIRST.find((key) => lower.includes(key));
  return thaiKey ? CATEGORY_HINTS[thaiKey]! : null;
}
